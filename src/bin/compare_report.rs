//! Comparison report generator — runs after `cargo bench --bench compare`.
//!
//! Reads Criterion's `estimates.json` files and produces a markdown
//! table comparing neuron's inference performance against the
//! mainstream frameworks (ONNX Runtime, MNN, llama.cpp).
//!
//! ## Usage
//!
//! ```bash
//! cargo bench --bench compare
//! cargo run --release --bin compare-report
//! ```
//!
//! Outputs `target/compare-summary.md` with a markdown table.
//!
//! ## Output format
//!
//! The table has one row per backend (neuron-candle, ort, mnn,
//! llama.cpp) and one column per workload. A "not available" entry
//! indicates the backend wasn't built for this comparison.

use std::fs;
use std::path::Path;

fn main() {
    let estimates_dir = Path::new("target/criterion/compare");
    if !estimates_dir.exists() {
        eprintln!("No Criterion output found at {}. Run `cargo bench --bench compare` first.", estimates_dir.display());
        std::process::exit(1);
    }

    let mut md = String::new();
    md.push_str("# Inference Backend Comparison\n\n");
    md.push_str(&format!(
        "**Platform**: {} ({}) build, {}\n\n",
        std::env::consts::OS,
        std::env::consts::ARCH,
        if cfg!(target_pointer_width = "64") { "64-bit" } else { "32-bit" }
    ));
    md.push_str("Generated by `compare-report` after `cargo bench --bench compare`.\n\n");
    md.push_str("All times in nanoseconds (lower is better). Memory in MB.\n\n");

    let workloads = collect_workloads(estimates_dir);
    if workloads.is_empty() {
        eprintln!("No benchmark results found in {}", estimates_dir.display());
        std::process::exit(1);
    }

    md.push_str("| Backend |");
    for w in &workloads {
        md.push_str(&format!(" {} (ns) | {} (RSS MB) |", w, w));
    }
    md.push('\n');

    md.push_str("|---|");
    for _ in &workloads {
        md.push_str("---:|---:|");
    }
    md.push('\n');

    let backends = ["neuron-candle", "ort", "mnn", "llama.cpp"];
    for backend in &backends {
        md.push_str(&format!("| **{}** |", backend));
        for w in &workloads {
            let time = read_estimate(estimates_dir, w, backend);
            let mem = read_peak_rss(estimates_dir, w, backend);
            md.push_str(&format!(" {} | {} |", time, mem));
        }
        md.push('\n');
    }

    md.push_str("\n## Methodology\n\n");
    md.push_str("- **Platforms supported**: Linux, macOS, Windows. Other Unix variants\n");
    md.push_str("  compile but return 0 for memory fields.\n");
    md.push_str("- **Memory measurement**: RSS via `/proc/self/status` (Linux),\n");
    md.push_str("  `task_info` (macOS), or `GetProcessMemoryInfo` (Windows).\n");
    md.push_str("- **Workloads**: YOLOv8 detection forward pass on 640×640 RGB,\n");
    md.push_str("  and LLM single-token forward (no KV cache, 2048-token seq, 4096-dim hidden, 32 layers).\n");
    md.push_str("- **neuron-candle**: pure-Rust via HuggingFace `candle` crate.\n");
    md.push_str("- **ort**: Microsoft's ONNX Runtime (gated by `feature = \"ort\"` in Cargo.toml).\n");
    md.push_str("- **mnn**: Alibaba MNN. v1.0: stub (binding not yet wired).\n");
    md.push_str("- **llama.cpp**: ggml-based reference. v1.0: stub for non-LLM workloads.\n");
    md.push_str("- \"not available\" entries indicate the backend wasn't built for this comparison.\n");
    md.push_str("- Run `cargo bench --release` for real performance data; debug builds are 10-100x slower.\n");

    let out_path = "target/compare-summary.md";
    fs::write(out_path, &md).expect("failed to write compare-summary.md");
    println!("Wrote {}", out_path);
    println!("\n{}", md);
}

/// Walk target/criterion/compare/ looking for benchmark group names.
fn collect_workloads(estimates_dir: &Path) -> Vec<String> {
    let mut workloads = Vec::new();
    if let Ok(entries) = fs::read_dir(estimates_dir) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            // Criterion dirs for groups look like: yolov8_detection_640x640
            // Skip base + report files
            if entry.path().is_dir() && name != "base" && name != "report" {
                workloads.push(name);
            }
        }
    }
    workloads.sort();
    workloads
}

/// Read the mean estimate (point estimate) for a (workload, backend)
/// pair from Criterion's estimates.json.
fn read_estimate(estimates_dir: &Path, workload: &str, backend: &str) -> String {
    let path = estimates_dir.join(workload).join(backend).join("base/estimates.json");
    if !path.exists() {
        return "not available".to_string();
    }
    let Ok(content) = fs::read_to_string(&path) else {
        return "not available".to_string();
    };
    let Ok(json) = serde_json::from_str::<serde_json::Value>(&content) else {
        return "not available".to_string();
    };
    let mean = json
        .get("mean")
        .and_then(|v| v.get("point_estimate"))
        .and_then(|v| v.as_f64());
    match mean {
        Some(ns) => format!("{:.0}", ns),
        None => "not available".to_string(),
    }
}

/// Read peak RSS in MB for a (workload, backend) pair. Criterion's
/// `estimates.json` has a `typical` section; we also look for
/// custom.json which our compare bench writes for memory data.
fn read_peak_rss(estimates_dir: &Path, workload: &str, backend: &str) -> String {
    // First try our custom memory data file
    let mem_path = estimates_dir.join(workload).join(backend).join("base/memory.json");
    if let Ok(content) = fs::read_to_string(&mem_path) {
        if let Ok(json) = serde_json::from_str::<serde_json::Value>(&content) {
            if let Some(rss) = json.get("peak_rss_bytes").and_then(|v| v.as_u64()) {
                return format!("{:.1}", rss as f64 / 1_048_576.0);
            }
        }
    }
    "n/a".to_string()
}
